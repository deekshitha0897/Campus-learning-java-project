class Logic4 
{
    public static void main(String args[])
    {
        int a=100;
        System.out.println("a = " + a);
        int b=--a;
        System.out.println("b = " + b);
        int c=a++;
        System.out.println("c = " + c);
        int d=--a;
        System.out.println("d = " + d);
        int e=++a;
        System.out.println("e = " + e);
        int f=a++;
        System.out.println("f = " + f);
    }
    
}
