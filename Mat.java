 class Mat 
 {
    public static void main(String args[])
    {
        int[][] matrix = new int [2][2];
        matrix[0][0] = 100;
        matrix[0][1] = 200; 
        matrix[1][0] = 300;
        matrix[1][1] = 400;  
        System.out.println("The 2x2 Matrix is :");
        System.out.println(matrix[0][0] + " " + matrix[0][1]);
        System.out.println(matrix[1][0] + " " + matrix[1][1]);

    }
    
}
