 class Arithmetic 
 {
    public static void main(String args[]) 
    {
        int a = 10;
        int b = 20;
        int c = a + b;
        int d = a - b;
        int e = a * b;
        int f = a / b;
        System.out.println("Sum of a and b is: " + c);
        System.out.println("Sub of a and b is: " + d);
        System.out.println("Product of a and b is: " + e);
        System.out.println("Div of a and b is: " + f);
    }

    
}
